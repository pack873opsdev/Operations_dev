BEGIN;
CREATE TABLE IF NOT EXISTS public.volunteer_roles (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 role_name text NOT NULL UNIQUE CHECK (length(trim(role_name)) BETWEEN 1 AND 120),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.volunteers (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 volunteer_name text NOT NULL CHECK (length(trim(volunteer_name)) BETWEEN 1 AND 160),
 email text NOT NULL UNIQUE CHECK (length(trim(email)) BETWEEN 3 AND 254),
 phone text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now()
);
-- Preserve the current committee records and use them to populate both master lists.
INSERT INTO public.volunteer_roles(role_name)
SELECT DISTINCT trim(role_name) FROM public.committee_roles WHERE nullif(trim(role_name),'') IS NOT NULL
ON CONFLICT (role_name) DO NOTHING;
INSERT INTO public.volunteers(volunteer_name,email,phone)
SELECT DISTINCT ON (lower(trim(email))) trim(volunteer_name), trim(email), coalesce(phone,'')
FROM public.committee_roles WHERE nullif(trim(email),'') IS NOT NULL AND nullif(trim(volunteer_name),'') IS NOT NULL
ORDER BY lower(trim(email)), id DESC
ON CONFLICT (email) DO NOTHING;
ALTER TABLE public.committee_roles ADD COLUMN IF NOT EXISTS role_master_id bigint REFERENCES public.volunteer_roles(id) ON DELETE RESTRICT;
ALTER TABLE public.committee_roles ADD COLUMN IF NOT EXISTS volunteer_id bigint REFERENCES public.volunteers(id) ON DELETE RESTRICT;
UPDATE public.committee_roles c SET role_master_id=r.id FROM public.volunteer_roles r WHERE c.role_master_id IS NULL AND trim(c.role_name)=r.role_name;
UPDATE public.committee_roles c SET volunteer_id=v.id FROM public.volunteers v WHERE c.volunteer_id IS NULL AND lower(trim(c.email))=lower(v.email);
CREATE INDEX IF NOT EXISTS committee_roles_role_master_id_idx ON public.committee_roles(role_master_id);
CREATE INDEX IF NOT EXISTS committee_roles_volunteer_id_idx ON public.committee_roles(volunteer_id);
-- Keep the existing snapshot fields current so the deployed Gmail Edge Function continues to work.
CREATE OR REPLACE FUNCTION public.pack873_dev_sync_committee_assignment() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE r public.volunteer_roles%ROWTYPE; v public.volunteers%ROWTYPE;
BEGIN
 IF NEW.role_master_id IS NOT NULL THEN
  SELECT * INTO r FROM public.volunteer_roles WHERE id=NEW.role_master_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown role'; END IF;
  NEW.role_name := r.role_name;
 END IF;
 IF NEW.volunteer_id IS NOT NULL THEN
  SELECT * INTO v FROM public.volunteers WHERE id=NEW.volunteer_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Unknown volunteer'; END IF;
  NEW.volunteer_name := v.volunteer_name; NEW.email := v.email; NEW.phone := v.phone;
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS pack873_dev_assignment_sync ON public.committee_roles;
CREATE TRIGGER pack873_dev_assignment_sync BEFORE INSERT OR UPDATE ON public.committee_roles
FOR EACH ROW EXECUTE FUNCTION public.pack873_dev_sync_committee_assignment();
-- Reflect later master-list edits in assignment snapshots (including email recipients).
CREATE OR REPLACE FUNCTION public.pack873_dev_refresh_assignment_snapshots() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
BEGIN
 IF TG_TABLE_NAME='volunteer_roles' THEN
  UPDATE public.committee_roles SET role_name=NEW.role_name WHERE role_master_id=NEW.id;
 ELSE
  UPDATE public.committee_roles SET volunteer_name=NEW.volunteer_name,email=NEW.email,phone=NEW.phone WHERE volunteer_id=NEW.id;
 END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS pack873_dev_role_master_refresh ON public.volunteer_roles;
CREATE TRIGGER pack873_dev_role_master_refresh AFTER UPDATE OF role_name ON public.volunteer_roles
FOR EACH ROW EXECUTE FUNCTION public.pack873_dev_refresh_assignment_snapshots();
DROP TRIGGER IF EXISTS pack873_dev_volunteer_master_refresh ON public.volunteers;
CREATE TRIGGER pack873_dev_volunteer_master_refresh AFTER UPDATE OF volunteer_name,email,phone ON public.volunteers
FOR EACH ROW EXECUTE FUNCTION public.pack873_dev_refresh_assignment_snapshots();
ALTER TABLE public.volunteer_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.volunteers ENABLE ROW LEVEL SECURITY;
-- Authenticated members can read directory options, but only admins can change them.
DROP POLICY IF EXISTS pack873_dev_roles_read ON public.volunteer_roles;
CREATE POLICY pack873_dev_roles_read ON public.volunteer_roles FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS pack873_dev_volunteers_read ON public.volunteers;
CREATE POLICY pack873_dev_volunteers_read ON public.volunteers FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS pack873_dev_roles_admin ON public.volunteer_roles;
CREATE POLICY pack873_dev_roles_admin ON public.volunteer_roles FOR ALL TO authenticated
USING ((auth.jwt()->'app_metadata'->>'pack873_role')='admin')
WITH CHECK ((auth.jwt()->'app_metadata'->>'pack873_role')='admin');
DROP POLICY IF EXISTS pack873_dev_volunteers_admin ON public.volunteers;
CREATE POLICY pack873_dev_volunteers_admin ON public.volunteers FOR ALL TO authenticated
USING ((auth.jwt()->'app_metadata'->>'pack873_role')='admin')
WITH CHECK ((auth.jwt()->'app_metadata'->>'pack873_role')='admin');
GRANT SELECT,INSERT,UPDATE,DELETE ON public.volunteer_roles,public.volunteers TO authenticated;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
COMMIT;
