-- Reconstructed base schema for fresh DEV installations; existing rows are preserved.
BEGIN;
CREATE TABLE IF NOT EXISTS public.committee_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_name text NOT NULL,
  volunteer_name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL DEFAULT ''
);
ALTER TABLE public.committee_roles ENABLE ROW LEVEL SECURITY;
CREATE POLICY pack873_committee_admin_write ON public.committee_roles FOR ALL TO authenticated
USING (auth.jwt()->'app_metadata'->>'pack873_role'='admin')
WITH CHECK (auth.jwt()->'app_metadata'->>'pack873_role'='admin');
GRANT SELECT,INSERT,UPDATE,DELETE ON public.committee_roles TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.committee_roles_id_seq TO authenticated;
COMMIT;
