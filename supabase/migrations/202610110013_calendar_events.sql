BEGIN;
CREATE TABLE IF NOT EXISTS public.calendar_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_name text NOT NULL CHECK (length(btrim(event_name))>0),
 audience text NOT NULL CHECK (audience IN ('Whole Pack','Lion','Tiger','Wolf','Bear','Webelos','Arrow of Light')),
 event_date date NOT NULL,
 place text NOT NULL CHECK (length(btrim(place))>0),
 address text NOT NULL CHECK (length(btrim(address))>0),
 start_time time NOT NULL,
 end_time time NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (end_time>start_time)
);
CREATE INDEX IF NOT EXISTS calendar_events_date_idx ON public.calendar_events(event_date,start_time);
ALTER TABLE public.calendar_events ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.calendar_events TO anon,authenticated;
GRANT INSERT,UPDATE ON public.calendar_events TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.calendar_events_id_seq TO authenticated;
CREATE POLICY calendar_public_read ON public.calendar_events FOR SELECT TO anon,authenticated USING (true);
CREATE POLICY calendar_admin_insert ON public.calendar_events FOR INSERT TO authenticated WITH CHECK (public.pack873_directory_access(true));
CREATE POLICY calendar_admin_update ON public.calendar_events FOR UPDATE TO authenticated USING (public.pack873_directory_access(true)) WITH CHECK (public.pack873_directory_access(true));
COMMIT;
